\set ON_ERROR_STOP on
BEGIN;
CREATE TABLE accounts (
  id integer PRIMARY KEY,
  name text NOT NULL UNIQUE
);
CREATE TABLE orders (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id integer NOT NULL REFERENCES accounts(id),
  amount_cents integer NOT NULL CHECK (amount_cents >= 0),
  description text NOT NULL
);
INSERT INTO accounts
SELECT n, 'account-' || lpad(n::text, 3, '0') FROM generate_series(1,100) n;
INSERT INTO orders(id, account_id, amount_cents, description)
SELECT n, ((n-1) % 100)+1, n*17, 'order-' || lpad(n::text,4,'0')
FROM generate_series(1,1000) n;
SELECT setval(pg_get_serial_sequence('orders','id'), 1000, true);
GRANT SELECT ON ALL TABLES IN SCHEMA public TO reader;
COMMIT;
NOTIFY pgrst, 'reload schema';
